export function translator(hass) {
  const strings = (hass?.locale?.language || hass?.language || "nl").startsWith("nl")
    ? nl
    : en;
  return (key, values = {}) =>
    (strings[key] ?? en[key] ?? key).replace(/\{(\w+)\}/g, (_, name) => values[name] ?? "");
}
